/**
 * Takes the mistakes listed in LAB_LIST_FIXES out of the lab's lists of name variants.
 * @param groups - The lab's lists.
 * @returns The lists without them.
 */
export function fixLabVariants(groups: string[][]): string[][] {
  return groups.map((group) => {
    const drop = new Set(LAB_LIST_FIXES.filter(([anchor]) => group.includes(anchor)).flatMap(([, names]) => names));
    return drop.size > 0 ? group.filter((name) => !drop.has(name)) : group;
  });
}
