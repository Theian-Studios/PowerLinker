/** Names only in the men's lists, and names only in the women's: one in both, like Jean or Pat, could be either. */
const men = new Set([...MEN.flat(), ...OTHER_MEN]);
const women = new Set([...WOMEN.flat(), ...OTHER_WOMEN]);

/**
 * Says whether a given name is a man's or a woman's, when the lists know it and it isn't used for both.
 * @param name - One given name, lowercase, without accents.
 * @returns "male", "female", or undefined.
 */
export function nameSex(name: string): "male" | "female" | undefined {
  if (EITHER.has(name)) return undefined;
  if (men.has(name) && !women.has(name)) return "male";
  if (women.has(name) && !men.has(name)) return "female";
  return undefined;
}

